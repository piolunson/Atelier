type Leaf = string;
type Tree = { [k: string]: Leaf | Tree };

function lookup(path: string): string {
  const parts = path.split(".");
  let cur: Leaf | Tree | undefined = pl as unknown as Tree;
  for (const part of parts) {
    if (!cur || typeof cur === "string") return path;
    cur = cur[part];
  }
  return typeof cur === "string" ? cur : path;
}

export function t(path: string, vars?: Record<string, string | number>): string {
  let text = lookup(path);
  text = text.replaceAll("{APP_NAME}", APP_NAME).replaceAll("{rok}", String(new Date().getFullYear()));
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${key}}`, String(value));
    }
  }
  return text;
}
